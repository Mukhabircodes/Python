#Loops
#loops through a range 
for i in range(5):
    print(i)
    
# Loops with start and end >(range(start, stop))
for i in range(1,6):
    print(i)
  
#loops with start, stop and step >(range(sart, stop, step))
for i in range(0,10,2):
    print(i)
    
#Loop through a list 
fruits = ['banana', 'orange', 'pineapple', 'cherry']
for fruit in fruits:
        print(fruit)
