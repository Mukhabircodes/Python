#if temperature is greater than 30 then we print that it's a hot day, otherwiseif it's less than 10 it's a cold day otherwise it's neither a hot nora cold day
temperature = 33

if temperature > 30:
    print("it's a hot day!")
elif temperature < 10:
    print("It's a cold day!")
else:
    print("It's neither hot nor cold")